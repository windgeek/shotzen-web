#!/usr/bin/env python3
"""Write the redirect pages that send every old URL to its new home on songli.me.

The support and privacy pages moved to https://songli.me/apps/shotzen/ on
2026-10-17. App Store Connect and older links may still point here, so each old
address keeps working: same page type, same language.

The old site served every language from one page and picked it from `?lang=`,
the choice saved in localStorage, then the browser language. The redirect
follows the same order. Without JavaScript it falls back to English and lists
every language.
"""
import json
from html import escape
from pathlib import Path

root = Path(__file__).resolve().parent.parent
new = "https://songli.me/apps/shotzen"
# English first: it has no language segment on songli.me.
names = {"en": "English", "zh-Hans": "简体中文", "zh-Hant": "繁體中文", "ja": "日本語", "ko": "한국어",
         "de": "Deutsch", "fr": "Français", "es": "Español", "pt-BR": "Português (Brasil)"}

# Same normalisation as the old shotzen.js: zh-TW/HK/MO -> zh-Hant, any pt -> pt-BR.
script = """(function(){var L=%s;
function n(t){if(typeof t!=="string")return null;var p=t.trim().toLowerCase().replace(/_/g,"-").split("-"),b=p[0];
if(b==="zh"){if(p.indexOf("hant")>=0)return"zh-Hant";if(p.indexOf("hans")>=0)return"zh-Hans";
return p.some(function(x){return["tw","hk","mo"].indexOf(x)>=0})?"zh-Hant":"zh-Hans"}
if(b==="pt")return"pt-BR";for(var i=0;i<L.length;i++)if(L[i].toLowerCase()===b)return L[i];return null}
function pick(){var q=n(new URLSearchParams(location.search).get("lang"));if(q)return q;
try{var s=n(localStorage.getItem("shotzen.lang"));if(s)return s}catch(e){}
var l=navigator.languages||[navigator.language];for(var j=0;j<l.length;j++){var m=n(l[j]);if(m)return m}return"en"}
var g=pick();location.replace("%s/"+(g==="en"?"":g+"/"))})();"""


def page(kind):
    base = f"{new}/{kind}"
    en = escape(f"{base}/")
    links = " · ".join(
        f'<a href="{escape(base + "/" + ("" if code == "en" else code + "/"))}" lang="{code}" hreflang="{code}">{escape(name)}</a>'
        for code, name in names.items())
    return f"""<!doctype html>
<!-- Generated by scripts/generate.py -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="robots" content="noindex">
<script>{script % (json.dumps(list(names)), base)}</script>
<noscript><meta http-equiv="refresh" content="0; url={en}"></noscript>
<link rel="canonical" href="{en}">
<title>ShotZen</title>
<style>body{{background:#0b0d10;color:#e9e6df;font:16px/1.7 -apple-system,sans-serif;display:grid;place-items:center;min-height:100vh;margin:0;padding:0 16px;text-align:center}}a{{color:#c9b98f}}</style>
</head>
<body><main><p>ShotZen {"support" if kind == "support" else "privacy policy"} has moved. <a href="{en}">{en}</a></p><p>{links}</p></main></body>
</html>
"""


(root / "index.html").write_text(page("support"))
(root / "privacy.html").write_text(page("privacy"))
print("2 redirect pages written")
